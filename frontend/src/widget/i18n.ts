export const STRINGS: Record<UiLang, Strings> = { ko, en, ja, zh }

export const LangContext = createContext<UiLang>('ko')

export function useStrings(): Strings {
  return STRINGS[useContext(LangContext)]
}

/** 처음 열 때의 화면 언어: 위젯을 붙인 페이지의 <html lang>이 en·ja·zh면 그 언어, 아니면 한국어 */
export function initialLang(): UiLang {
  const page = document.documentElement.lang.toLowerCase().slice(0, 2)
  return page === 'en' || page === 'ja' || page === 'zh' ? page : 'ko'
}
